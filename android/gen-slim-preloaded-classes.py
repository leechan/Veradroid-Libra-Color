"""从 AOSP 的 frameworks/base/preloaded-classes 生成阅读器用的精简版（device/veradroid/kindle/slim/preloaded-classes）。

preloaded-classes 有两个用途：编译时它是 boot 镜像的 --image-classes（决定 boot.art 里预先初始化好的类），
运行时 zygote 开机把它们逐个 Class.forName 一遍，之后每个应用进程都带着这些类（共享页）。
墨水屏阅读器用不到的整块功能（电话、短信、蓝牙、NFC、相机、音视频、打印、语音、OpenGL……）留在里面只是
让 zygote 开机多做事、多占一份常驻内存；去掉后用到的进程自己按需加载，功能不受影响（类还在 boot classpath 里）。

用法：python3 gen-slim-preloaded-classes.py <aosp>/frameworks/base/preloaded-classes > device/veradroid/kindle/slim/preloaded-classes
"""
import sys
DROP = (
    "android.telephony.", "android.telecom.", "com.android.internal.telephony.", "com.android.ims.", "android.net.sip.", "android.net.rtp.",
    "android.bluetooth.", "android.nfc.",
    "android.hardware.camera2.", "android.hardware.Camera", "android.hardware.soundtrigger.", "android.hardware.radio.",
    "android.hardware.location.", "android.hardware.usb.", "android.hardware.fingerprint.", "android.hardware.hdmi.",
    "android.media.", "android.mtp.", "android.drm.", "android.speech.", "android.print.", "android.printservice.",
    "android.gesture.", "android.service.dreams.", "android.service.wallpaper.", "android.service.voice.", "android.service.carrier.",
    "android.opengl.", "javax.microedition.khronos.", "android.renderscript.", "android.net.wifi.p2p.", "android.net.nsd.",
    "android.appwidget.", "android.app.backup.", "android.location.Gps", "android.location.Gnss",
)
def base(name):                      # "[Landroid.media.Foo;" / "[[Landroid..." -> "android.media.Foo"
    n = name.lstrip("[")
    return n[1:].rstrip(";") if n.startswith("L") and name.startswith("[") else n
kept = dropped = 0
out = ["# VeraDroid slim preloaded-classes: generated by android/gen-slim-preloaded-classes.py, do not edit by hand."]
for line in open(sys.argv[1], encoding="utf-8"):
    s = line.strip()
    if not s or s.startswith("#"):
        continue
    if base(s).startswith(DROP):
        dropped += 1
        continue
    kept += 1
    out.append(s)
sys.stdout.write("\n".join(out) + "\n")
sys.stderr.write("kept %d, dropped %d\n" % (kept, dropped))
